# Ошибки

# Обработать:

# - пустое выражение;
# - недопустимый символ;
# - пропущенный операнд;
# - два бинарных оператора подряд;
# - деление на ноль;
# - неизвестную единицу;
# - несовместимые единицы;
# - неверное числовое значение.

# CLI выводит ошибку в stderr и завершается с кодом `2`. Успешная команда завершается с кодом `0`.